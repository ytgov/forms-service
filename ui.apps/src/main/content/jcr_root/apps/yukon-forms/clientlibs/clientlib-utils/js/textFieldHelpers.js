/** Converts a character code into a string
 *
@name charCodeToString
@param {number} Character code
@return {string} A single-character string with the character whose code was provided
 */
function charCodeToString(charCode) {
	return String.fromCharCode(charCode);
}

/** Gets character code for 'a'
 *
@name getLowercaseACode
@return {number} Code for 'a'
 */
function getLowercaseACode() {
	return 97;
}

/** Gets character code for 'A'
 *
@name getUppercaseACode
@return {number} Code for 'A'
 */
function getUppercaseACode() {
	return 65;
}

